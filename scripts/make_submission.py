#!/usr/bin/env python3
"""Build the ERL submission package from the final Markdown (paper-covert). Read-only on output/manuscript/.

  output/submission/latex/      main.tex (inputs only), preamble.tex, metadata.tex, sections/*.tex,
                                figures/, si.tex + si/*.tex, build.sh
  output/submission/pdf/        MANUSCRIPT_SUBMISSION_READY.pdf, SUPPLEMENTARY_INFORMATION.pdf
  output/submission/docx/       MANUSCRIPT_SUBMISSION_READY.docx, SUPPLEMENTARY_INFORMATION.docx

Sections come from output/manuscript/sections_revised/ (front matter stripped, heading numbers removed so
LaTeX numbers them). Figures 1-5 are placed after the Results with captions from
output/figures/FIGURE_CAPTIONS.md. References are kept as the manuscript's formatted IOP Harvard list
(author-year citations in the text are plain text; no BibTeX). Prose is not edited.
Engine: XeLaTeX (Unicode text: ×, ≥, ², √). Class: article (no IOP class installed; re-wrap with
iopart / the IOP template at submission).

    python scripts/make_submission.py
"""
import glob
import os
import re
import shutil
import subprocess

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MS = os.path.join(R, "output", "manuscript")
SEC = os.path.join(MS, "sections_revised")
FIG = os.path.join(R, "output", "figures")
OUT = os.path.join(R, "output", "submission")
LT = os.path.join(OUT, "latex")
MAIN_FIGS = ["Fig01_concentration", "Fig02_robustness", "Fig03_peat_traits", "Fig04_landprep", "Fig05_timing_drought"]
SI_FIGS = ["FigS1_flag_calibration", "FigS2_ignitions_by_dc", "FigS3_two_seasons"]

PREAMBLE = r"""% preamble.tex — generated by scripts/make_submission.py (paper-covert)
\usepackage{fontspec}
\setmainfont{Times New Roman}
\usepackage[a4paper,margin=2.5cm]{geometry}
\usepackage{setspace}
\onehalfspacing
\usepackage{graphicx}
\usepackage{booktabs,longtable,array,calc,multirow}
\usepackage{caption}
\captionsetup{font=small,labelfont=bf}
\usepackage{float}
\usepackage{xcolor}
\usepackage[hidelinks]{hyperref}
\usepackage{lineno}
\providecommand{\tightlist}{\setlength{\itemsep}{0pt}\setlength{\parskip}{0pt}}
\newcounter{none}  % pandoc 3 longtables without a caption use \LTcaptype{none}
\setlength{\LTleft}{0pt}
\setlength{\LTright}{0pt}
\newcommand{\figpending}{\textcolor{red!70!black}{\textbf{[FIGURE PENDING]}}}
\usepackage{mdframed}
\newmdenv[linecolor=red!70!black,backgroundcolor=red!5,linewidth=0.6pt]{placeholder}
"""


def strip_front(t):
    return re.sub(r"\A---\n.*?\n---\n", "", t, flags=re.S)


def denumber(md):
    return re.sub(r"^(#+)\s+\d+(?:\.\d+)*\.?\s+", r"\1 ", md, flags=re.M)


def pandoc(md, to="latex", extra=()):
    r = subprocess.run(["pandoc", "-f", "markdown-auto_identifiers+pipe_tables", "-t", to, "--wrap=preserve", *extra],
                       input=md, capture_output=True, text=True, check=True)
    return r.stdout


def captions():
    t = open(os.path.join(FIG, "FIGURE_CAPTIONS.md")).read()
    out = {}
    for m in re.finditer(r"\*\*Figure (\d+)\.\*\*(.*?)(?=\n\s*\n\*\*Figure |\Z)", t, re.S):
        out[int(m.group(1))] = m.group(2).strip()
    return out


def figure_block(stem, cap_md, label):
    cap = pandoc(cap_md).strip()
    return ("\\begin{figure}[p]\n\\centering\n"
            f"\\includegraphics[width=\\textwidth,height=0.8\\textheight,keepaspectratio]{{figures/{stem}.pdf}}\n"
            f"\\caption{{{cap}}}\n\\label{{fig:{label}}}\n\\end{{figure}}\n")


def main():
    for d in ("latex/sections", "latex/si", "latex/figures", "pdf", "docx"):
        os.makedirs(os.path.join(OUT, d), exist_ok=True)
    # ---------- metadata
    title_md = strip_front(open(os.path.join(SEC, "00_title.md")).read())
    title = re.search(r"^# (.+)$", title_md, re.M).group(1).strip()
    kw = re.search(r"\*\*Keywords:\*\*\s*(.+)", title_md).group(1).strip()
    open(os.path.join(LT, "preamble.tex"), "w").write(PREAMBLE)
    open(os.path.join(LT, "metadata.tex"), "w").write(
        "% metadata.tex — generated\n"
        f"\\title{{{pandoc(title).strip()}}}\n"
        "\\author{[AUTHOR BLOCK — to be completed]}\n\\date{}\n"
        f"\\newcommand{{\\keywordlist}}{{{pandoc(kw).strip()}}}\n"
        "\\newcommand{\\articletype}{Letter, \\textit{Environmental Research Letters}}\n")
    # ---------- sections
    caps = captions()
    files = [("01_abstract.md", "01_abstract"), ("02_introduction.md", "02_introduction"),
             ("03_data_methods.md", "03_data_methods"), ("04_results.md", "04_results"),
             ("05_discussion.md", "05_discussion"), ("06_conclusion.md", "06_conclusion"),
             ("07_declarations.md", "07_declarations")]
    inputs, md_all = [], ["# " + title + "\n\n" + "\n".join(l for l in title_md.splitlines()[1:])]
    for src, stem in files:
        md = strip_front(open(os.path.join(SEC, src)).read())
        md_all.append(md)
        if stem == "01_abstract":
            body = re.sub(r"^# Abstract\s*", "", md.strip())
            tex = ("\\begin{abstract}\n" + pandoc(body) + "\\end{abstract}\n\n"
                   "\\noindent\\textbf{Keywords:} \\keywordlist\n\n\\noindent\\textbf{Article type:} \\articletype\n")
        else:
            tex = pandoc(denumber(md))
            if stem == "07_declarations":
                for h in ("Data availability statement", "Acknowledgements", "Conflict of interest", "References"):
                    tex = tex.replace(f"\\section{{{h}}}", f"\\section*{{{h}}}")
            if stem == "04_results":
                tex = tex.replace("\\textbf{Table 1.}", "\\noindent\\textbf{Table 1.}")
                tex += "\n\\clearpage\n" + "".join(figure_block(MAIN_FIGS[i - 1], caps[i], f"{i}") for i in sorted(caps))
                md_all.append("\n".join(f"![**Figure {i}.** {caps[i]}](../figures/{MAIN_FIGS[i - 1]}.png)\n" for i in sorted(caps)))
        open(os.path.join(LT, "sections", stem + ".tex"), "w").write(tex)
        inputs.append(stem)
    for stem in MAIN_FIGS + SI_FIGS:
        shutil.copy(os.path.join(FIG, stem + ".pdf"), os.path.join(LT, "figures", stem + ".pdf"))
    open(os.path.join(LT, "main.tex"), "w").write(
        "% main.tex — generated by scripts/make_submission.py (paper-covert)\n"
        "% Venue: Environmental Research Letters (Letter). Class: article (re-wrap with the IOP template at submission).\n"
        "\\documentclass[11pt]{article}\n\\input{preamble}\n\\input{metadata}\n\\begin{document}\n\\maketitle\n\\linenumbers\n"
        + "".join(f"\\input{{sections/{s}}}\n" for s in inputs) + "\\end{document}\n")
    # ---------- SI
    si_md = open(os.path.join(MS, "SUPPLEMENTARY.md")).read()
    si_title = "Supplementary Information"
    si_body = re.sub(r"\A# Supplementary Information\s*", "", si_md)
    si_body = re.sub(r"!\[Figure (S\d)\]\(\.\./figures/(\w+)\.png\)",
                     lambda m: f"![](figures/{m.group(2)}.pdf)", si_body)
    si_tex = pandoc(si_body)
    si_tex = re.sub(r"\\section\{(S\d+) ", r"\\section*{\1 ", si_tex)
    si_tex = si_tex.replace("\\section{References}", "\\section*{References}")
    si_tex = re.sub(r"\\pandocbounded\{(\\includegraphics)(\[[^\]]*\])?(\{[^}]*\})\}",
                    r"\\begin{center}\1[width=\\textwidth,height=0.45\\textheight,keepaspectratio]\3\\end{center}", si_tex)
    open(os.path.join(LT, "si", "si_body.tex"), "w").write(si_tex)
    open(os.path.join(LT, "si.tex"), "w").write(
        "% si.tex — Supplementary Information (generated)\n\\documentclass[10pt]{article}\n\\input{preamble}\n"
        "\\providecommand{\\pandocbounded}[1]{#1}\n"
        f"\\title{{{si_title}}}\n\\date{{}}\n\\begin{{document}}\n\\maketitle\n{{\\small\n\\input{{si/si_body}}\n}}\n\\end{{document}}\n")
    # ---------- build
    open(os.path.join(LT, "build.sh"), "w").write(
        "#!/usr/bin/env bash\nset -euo pipefail\ncd \"$(dirname \"$0\")\"\n"
        "for d in main si; do latexmk -xelatex -interaction=nonstopmode -halt-on-error \"$d.tex\" > \"$d.buildlog\" 2>&1 || "
        "{ echo \"BUILD FAILED: $d\"; grep -m5 -A3 '^!' \"$d.log\" || true; exit 1; }; done\n"
        "cp -f main.pdf ../pdf/MANUSCRIPT_SUBMISSION_READY.pdf\ncp -f si.pdf ../pdf/SUPPLEMENTARY_INFORMATION.pdf\n"
        "echo 'PDF build ok'\n")
    os.chmod(os.path.join(LT, "build.sh"), 0o755)
    b = subprocess.run(["bash", os.path.join(LT, "build.sh")], capture_output=True, text=True)
    print(b.stdout.strip(), b.stderr.strip()[:1500])
    # ---------- DOCX (from Markdown, images resolved relative to output/manuscript)
    md_main = "\n\n".join(md_all)
    open(os.path.join(OUT, "docx", "_main.md"), "w").write(md_main)
    for src, dst in ((os.path.join(OUT, "docx", "_main.md"), "MANUSCRIPT_SUBMISSION_READY.docx"),
                     (os.path.join(MS, "SUPPLEMENTARY.md"), "SUPPLEMENTARY_INFORMATION.docx")):
        d = subprocess.run(["pandoc", src, "-f", "markdown+pipe_tables", "-o", os.path.join(OUT, "docx", dst),
                            "--resource-path", MS], capture_output=True, text=True)
        print(dst, "ok" if d.returncode == 0 else "FAILED " + d.stderr[:400])
    os.remove(os.path.join(OUT, "docx", "_main.md"))


if __name__ == "__main__":
    main()
